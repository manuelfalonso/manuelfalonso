namespace SombraStudios.Shared.Extensions
{
    /// <summary>
    /// A single direction along one of a transform's local axes.
    /// </summary>
    public enum Direction
    {
        /// <summary>
        /// Upward direction.
        /// </summary>
        Up,

        /// <summary>
        /// Downward direction.
        /// </summary>
        Down,

        /// <summary>
        /// Left direction.
        /// </summary>
        Left,

        /// <summary>
        /// Right direction.
        /// </summary>
        Right,

        /// <summary>
        /// Forward direction.
        /// </summary>
        Forward,

        /// <summary>
        /// Backward direction.
        /// </summary>
        Backward
    }
}